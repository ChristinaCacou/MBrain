#!/usr/bin/env python3
"""Independent numerical checks of archived synthetic outputs.
No frozen-analysis source is imported. Does not validate a consciousness claim.
"""
from pathlib import Path
import csv, json, hashlib, itertools
import numpy as np
import pandas as pd
HERE=Path(__file__).resolve().parent
DATA=HERE/'audit'
BASE=DATA/'common_driver'
rows=[]
for condition in ['common_driver','no_change']:
    files=BASE if condition=='common_driver' else DATA/'no_change'
    meta=pd.read_csv(files/'SYNTHETIC_metadata.csv')
    fdir=files/'synthetic_trajectories'
    exported=pd.read_csv(files/'locked_outputs'/'cell_state_metrics.csv')
    # Recompute participation ratio independently using singular values, not eigvalsh(cov).
    diffs=[]
    n=0
    for r in meta.itertuples(index=False):
        x=np.load(fdir/r.trajectory_file)['trajectory']
        x=x-x[:20].mean(axis=0,keepdims=True)
        x=x/np.sqrt((x*x).sum())
        xc=x-x.mean(axis=0,keepdims=True)
        s=np.linalg.svd(xc,full_matrices=False,compute_uv=False)
        variances=s*s
        variances=variances[variances>1e-12]
        participation=(variances.sum()**2)/(variances**2).sum()
        q=exported[(exported.cell_id==r.cell_id)&(exported.state_code==r.state_code)&(exported.modality_code==r.modality_code)]
        assert len(q)==1,(r.cell_id,r.state_code,r.modality_code)
        diffs.append(abs(participation-float(q.iloc[0].effective_dimensionality)))
        n+=1
    d=exported[(exported.modality_code=='ELEC')]
    paired=d.pivot(index='cell_id',columns='state_code',values='effective_dimensionality')
    delta=paired.HAB-paired.BASE
    day_lookup=d[['cell_id','replicate_day']].drop_duplicates().set_index('cell_id').loc[paired.index].replicate_day
    day_means=delta.groupby(day_lookup).mean()
    null=np.array([np.mean(day_means.values*np.array(s)) for s in itertools.product([-1,1],repeat=len(day_means))])
    exact2=(np.abs(null)>=abs(day_means.mean())-1e-12).mean()
    rows.append({'condition':condition,'n_trials':n,'max_abs_svd_eigen_difference':max(diffs),
        'BASE_mean':paired.BASE.mean(),'HAB_mean':paired.HAB.mean(),
        'delta_mean':delta.mean(),'day_deltas':day_means.round(6).to_dict(),
        'exact_4day_two_sided_signflip_p':float(exact2)})
# Independent analytic check of the observational covariance construction.
rho=.6; gamma=.25; c=(rho-gamma)/rho; v=1-(gamma*gamma+c*c*rho+2*gamma*c*rho)
cov_me=gamma+c*rho
var_e=gamma*gamma+c*c*rho+2*gamma*c*rho+v
assert abs(cov_me-rho)<1e-14 and abs(var_e-1)<1e-14 and v>0
report={'kind':'independent arithmetic and numeric checks only',
    'computational':rows,'gaussian_identification':{'rho':rho,'gamma':gamma,'common_cause_model_covariance':rho,'directed_model_covariance':cov_me,'directed_model_E_variance':var_e,'directed_residual_variance':v},
    'caveats':['Synthetic data generated by original model; no independent biological measurement.',
               'Four recording days; the exact two-sided four-day signflip test cannot yield p<0.125.',
               'Frozen classifier and predictive-model permutation tests flip cells, not independent days.',
               'Rerun and SVD checks do not amount to a separately developed end-to-end implementation.']}
(HERE/'INDEPENDENT_ARITHMETIC_AUDIT.json').write_text(json.dumps(report,indent=2))
print(json.dumps(report,indent=2))
