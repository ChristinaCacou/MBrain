#!/usr/bin/env python3
"""Independent cross-check of synthetic common-driver results (no import of locked pipeline).
Input is the trajectory array and per-trial output generated by the original frozen analysis.
Checks summary numbers by reimplementing covariance participation ratio using singular values;
checks AUC from externally generated output table, evaluates day-level sign resolution, and
screens constant/degenerate markers. Explicitly post-hoc independent verification, not biology.
"""
import argparse, json, hashlib, itertools
from pathlib import Path
import numpy as np
import pandas as pd
from scipy.stats import ttest_1samp, binomtest
from sklearn.metrics import roc_auc_score
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression

p=argparse.ArgumentParser();p.add_argument('--audit-root',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args();a.output.mkdir(parents=True,exist_ok=True)
summary={}
for condition in ['common_driver','no_change']:
    root=a.audit_root/condition
    d=pd.read_csv(root/'locked_outputs'/'cell_state_metrics.csv')
    t=pd.read_csv(root/'locked_outputs'/'trial_metrics.csv')
    m=pd.read_csv(root/'SYNTHETIC_metadata.csv')
    rows=[]
    for _,r in m.iterrows():
        x=np.load(root/'synthetic_trajectories'/r.trajectory_file)['trajectory']
        x=x-x[:max(3,round(.2*len(x)))].mean(0,keepdims=True)
        x=x/np.linalg.norm(x)
        # Covariance eigenvalues equal squared singular values divided by n-1.
        sv=np.linalg.svd(x-x.mean(0,keepdims=True),full_matrices=False,compute_uv=False)
        dim=float(np.sum(sv**2)**2/np.sum(sv**4))
        rows.append((r.cell_id,r.state_code,r.modality_code,dim))
    ck=pd.DataFrame(rows,columns=['cell_id','state_code','modality_code','dim_independent'])
    joined=ck.merge(t,on=['cell_id','state_code','modality_code'],validate='one_to_one')
    maxdev=float(np.max(np.abs(joined.dim_independent-joined.effective_dimensionality)))
    ee=d[d.modality_code=='ELEC'].pivot(index=['cell_id','replicate_day'],columns='state_code',values='effective_dimensionality').reset_index()
    ee['diff']=ee.HAB-ee.BASE
    day=ee.groupby('replicate_day')['diff'].mean()
    vals=day.to_numpy()
    # Exact randomization reference if days are independently sign-symmetric, not a valid test by itself.
    flips=[np.mean(vals*np.array(s)) for s in itertools.product([-1,1],repeat=len(vals))]
    p_exact=float(np.mean(np.abs(flips)>=abs(vals.mean())-1e-12))
    feat=['effective_dimensionality','lz76_norm','compressed_complexity']
    mech=d[d.modality_code=='MECH'].copy();elec=d[d.modality_code=='ELEC'].copy()
    sc=StandardScaler().fit(mech[feat]);clf=LogisticRegression(C=1,solver='liblinear',random_state=260416,max_iter=1000).fit(sc.transform(mech[feat]),(mech.state_code=='HAB').astype(int))
    probs=clf.predict_proba(sc.transform(elec[feat]))[:,1];auc=float(roc_auc_score((elec.state_code=='HAB').astype(int),probs))
    dd=elec.copy();dd['score']=probs
    auc_days={str(day):float(roc_auc_score((g.state_code=='HAB').astype(int),g.score)) for day,g in dd.groupby('replicate_day')}
    summary[condition]={
        'trial_metrics_independent_svd_max_abs_error':maxdev,
        'n_cells':int(ee.shape[0]),
        'primary_mean_independently_recomputed':float(ee['diff'].mean()),
        'day_mean_primary_differences':{str(k):float(v) for k,v in day.items()},
        'day_level_exact_two_sided_signflip_p':p_exact,
        'day_level_sign_resolution_n':int(2**len(vals)),
        'auc_recomputed':auc,
        'auc_by_day':auc_days,
        'constant_features':{k:int(d[k].nunique()) for k in feat},
        'compressed_complexity_variance':float(d.compressed_complexity.var()),
        'n_days':int(day.size),
        'note':'The exact day sign-flip is a diagnostic sensitivity test under day-sign exchangeability, not a valid unconditional randomization test. Synthetic observations are not biological measurements.'
    }
    joined[['cell_id','replicate_day','state_code','modality_code','effective_dimensionality','dim_independent']].to_csv(a.output/f'{condition}_metric_crosscheck.csv',index=False)
# check the two-cases use exactly matched synthetic BASE trajectories
for feature in ['response_energy','effective_dimensionality','lz76_norm','compressed_complexity']:
    x=pd.read_csv(a.audit_root/'common_driver'/'locked_outputs'/'trial_metrics.csv')
    y=pd.read_csv(a.audit_root/'no_change'/'locked_outputs'/'trial_metrics.csv')
    b=x[x.state_code=='BASE'].merge(y[y.state_code=='BASE'],on=['cell_id','modality_code','state_code','replicate_day'],suffixes=('_change','_control'))
    summary.setdefault('paired_controls',{})[feature+'_baseline_max_abs_diff']=float(np.max(np.abs(b[feature+'_change']-b[feature+'_control'])))
(a.output/'INDEPENDENT_AUDIT_RESULTS.json').write_text(json.dumps(summary,indent=2)+'\n')
print(json.dumps({k:{x:v for x,v in r.items() if x in ('trial_metrics_independent_svd_max_abs_error','primary_mean_independently_recomputed','day_level_exact_two_sided_signflip_p','auc_recomputed','constant_features')} for k,r in summary.items() if isinstance(r,dict)},indent=2))
